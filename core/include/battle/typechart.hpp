// Returns the combined type multiplier as a rational numerator over 100.
// e.g. 200 = 2x, 50 = 0.5x, 0 = immune, 100 = neutral.
// For dual-type defenders, multiply both and divide by 100 to get final x100 value.
inline constexpr int effectiveness(Type atk, Type def1, Type def2 = Type::COUNT) noexcept {
    int a = (int)atk;
    int d1 = (int)def1;
    int e = TYPE_CHART[a][d1];
    if (def2 != Type::COUNT) {
        int d2 = (int)def2;
        e = e * TYPE_CHART[a][d2] / 100;
    }
    return e;
}

